CREATE TABLE IF NOT EXISTS cuentas(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,cliente_id BIGINT NOT NULL,tipo VARCHAR(20) NOT NULL,
 saldo NUMERIC(15,2) NOT NULL DEFAULT 0 CHECK(saldo>=0),estado VARCHAR(20) NOT NULL DEFAULT 'ACTIVA',fecha_apertura TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS operaciones(
 idempotencia VARCHAR(80) PRIMARY KEY,tipo VARCHAR(20) NOT NULL,cuenta_origen BIGINT REFERENCES cuentas(id),cuenta_destino BIGINT REFERENCES cuentas(id),
 monto NUMERIC(15,2) NOT NULL CHECK(monto>0),referencia VARCHAR(200),saldo_anterior NUMERIC(15,2),saldo_posterior NUMERIC(15,2),
 estado VARCHAR(20) NOT NULL DEFAULT 'CONFIRMADA',fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS operaciones_origen ON operaciones(cuenta_origen,fecha);
CREATE INDEX IF NOT EXISTS operaciones_destino ON operaciones(cuenta_destino,fecha);
CREATE TABLE IF NOT EXISTS eventos_pendientes(
 id VARCHAR(80) PRIMARY KEY REFERENCES operaciones(idempotencia),contenido TEXT NOT NULL,publicado BOOLEAN NOT NULL DEFAULT FALSE,
 intentos INTEGER NOT NULL DEFAULT 0,fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS historial_eventos(id VARCHAR(80) PRIMARY KEY,contenido TEXT NOT NULL,fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP);
